package com.mrivanplays.annotationconfig.toml;

import static com.mrivanplays.annotationconfig.toml.TomlTesting.RESOLVER;
import static com.mrivanplays.annotationconfig.toml.TomlTesting.parse;

import com.mrivanplays.annotationconfig.core.annotations.ConfigObject;
import com.mrivanplays.annotationconfig.core.annotations.comment.Comment;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/** A TOML file with the values TOML writes in a form of its own reads back. */
class TestTomlFiles {

  @Test
  void fileRoundTrip(@TempDir Path dir) throws IOException {
    Path file = dir.resolve("config.toml");
    RESOLVER.dump(new FileSubject(), file);
    parse(Files.readString(file));

    FileSubject loaded = new FileSubject();
    loaded.message = null;
    loaded.ratio = 0;
    loaded.section.a = 0;
    RESOLVER.load(loaded, file);
    Assertions.assertEquals("it's \"quoted\"\nand multi-line", loaded.message);
    Assertions.assertTrue(Double.isNaN(loaded.ratio));
    Assertions.assertEquals(1, loaded.section.a);
  }

  @Comment("Generated by AnnotationConfig")
  static class FileSubject {

    @Comment("The message")
    public String message = "it's \"quoted\"\nand multi-line";

    public double ratio = Double.NaN;

    @ConfigObject public Section section = new Section();
  }

  public static class Section {

    public int a = 1;
  }
}
