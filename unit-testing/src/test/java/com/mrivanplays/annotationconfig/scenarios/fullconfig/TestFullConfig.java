package com.mrivanplays.annotationconfig.scenarios.fullconfig;

import com.mrivanplays.annotationconfig.core.annotations.ConfigObject;
import com.mrivanplays.annotationconfig.core.annotations.Key;
import com.mrivanplays.annotationconfig.core.annotations.comment.Comment;
import com.mrivanplays.annotationconfig.scenarios.Format;
import com.mrivanplays.annotationconfig.scenarios.Scenario;
import com.mrivanplays.annotationconfig.scenarios.Sources;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.junit.jupiter.params.ParameterizedClass;
import org.junit.jupiter.params.provider.MethodSource;

/**
 * A config as an application has it, in every format with sections: written to a file and read
 * back, read from a file written by hand, and a file of an older version that gets the new options.
 */
@ParameterizedClass(name = "{0}")
@MethodSource(Sources.WITH_SECTIONS)
class TestFullConfig extends Scenario {

  TestFullConfig(Format format) {
    super(format, "full-config");
  }

  @Test
  void aWrittenFileLoadsBack(@TempDir Path dir) throws IOException {
    Path file = dir.resolve("config." + this.format.extension());
    this.resolver.dump(new Config(), file);
    assertOutput("config", Files.readString(file));

    Config config = new Config();
    config.name = null;
    config.messages.noConsole = null;
    config.list = List.of();
    config.location.x = 0;
    config.otherLocation = new Location("x", 0, 0, 0);
    config.section.baz = 0;
    config.section.enabled = false;
    this.resolver.load(config, file);
    Assertions.assertEquals("Ivan", config.name);
    Assertions.assertEquals("No console!", config.messages.noConsole);
    Assertions.assertEquals(List.of("Hello", "bla bla"), config.list);
    Assertions.assertEquals(20, config.location.x);
    Assertions.assertEquals("world_the_end", config.otherLocation.world);
    Assertions.assertEquals(333, config.otherLocation.z);
    Assertions.assertEquals(2.0, config.section.baz);
    Assertions.assertTrue(config.section.enabled);
  }

  @Test
  void aHandWrittenFileLoads() {
    Config config = load(new Config(), "config-read");
    Assertions.assertEquals("Pekov", config.name);
    Assertions.assertEquals("baz", config.foo);
    Assertions.assertEquals("Console only!", config.messages.consoleOnly);
    Assertions.assertEquals(List.of("one"), config.list);
    Assertions.assertEquals(5, config.a);
    Assertions.assertEquals("nether", config.location.world);
    Assertions.assertEquals("foo", config.otherLocation.world);
    Assertions.assertEquals(1, config.otherLocation.x);
    Assertions.assertEquals(223, config.otherLocation.y);
    Assertions.assertEquals(445, config.otherLocation.z);
    Assertions.assertEquals(3, config.section.bar);
    Assertions.assertFalse(config.section.enabled);
  }

  @Test
  void aFileOfAnOlderVersionGetsTheNewOptions(@TempDir Path dir) throws IOException {
    Path file = dir.resolve("config." + this.format.extension());
    this.resolver.dump(new OlderConfig(), file);
    Config config = new Config();
    // set, as TOML keeps it off by default
    this.resolver.load(config, file, generateNewOptions());
    Assertions.assertEquals("older", config.name);
    Assertions.assertEquals(1, config.a);
    Assertions.assertEquals("world_the_end", config.otherLocation.world);
    assertOutput("config-upgraded", Files.readString(file));
  }

  // <editor-fold desc="subjects">

  @Comment("Generated by AnnotationConfig")
  static class Config {

    @Comment("name")
    @Key("custom-name")
    private String name = "Ivan";

    @Comment("foo")
    private String foo = "bar";

    @ConfigObject private Messages messages = new Messages();

    @Comment("this is a list")
    private List<String> list = List.of("Hello", "bla bla");

    @Comment("baz")
    private int a = 1;

    @ConfigObject private LocationSection location = new LocationSection();

    @Comment("Another location")
    @Key("other-location")
    private Location otherLocation = new Location("world_the_end", 200, 22, 333);

    @ConfigObject
    @Key("new-section")
    private NewSection section = new NewSection();
  }

  // Config before the options a, other-location and new-section were added
  @Comment("Generated by AnnotationConfig")
  static class OlderConfig {

    @Comment("name")
    @Key("custom-name")
    private String name = "older";

    @Comment("foo")
    private String foo = "bar";

    @ConfigObject private Messages messages = new Messages();

    @Comment("this is a list")
    private List<String> list = List.of("Hello", "bla bla");

    @ConfigObject private LocationSection location = new LocationSection();
  }

  @Comment("All supported messages")
  public static class Messages {

    @Key("no-console")
    private String noConsole = "No console!";

    @Key("console-only")
    private String consoleOnly = "This command is console only!";
  }

  @Comment("The location of the player")
  public static class LocationSection {

    private String world = "world";
    private int x = 20;
    private int y = 2;
    private int z = 1;
  }

  // a custom data type without an empty constructor: read into the instance the field holds
  public static class Location {

    private String world;
    private int x;
    private int y;
    private int z;

    Location(String world, int x, int y, int z) {
      this.world = world;
      this.x = x;
      this.y = y;
      this.z = z;
    }
  }

  @Comment("This is some dummy section")
  public static class NewSection {

    private String foo = "foo";
    private int bar = 2;
    private double baz = 2.0;
    private boolean enabled = true;
  }

  // </editor-fold>
}
