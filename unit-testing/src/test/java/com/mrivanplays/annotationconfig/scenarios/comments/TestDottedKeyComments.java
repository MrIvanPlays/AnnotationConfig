package com.mrivanplays.annotationconfig.scenarios.comments;

import com.mrivanplays.annotationconfig.core.annotations.Key;
import com.mrivanplays.annotationconfig.core.annotations.comment.Comment;
import com.mrivanplays.annotationconfig.scenarios.Format;
import com.mrivanplays.annotationconfig.scenarios.Scenario;
import com.mrivanplays.annotationconfig.scenarios.Sources;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedClass;
import org.junit.jupiter.params.provider.MethodSource;

/**
 * Comments of a config without sections, whose keys are dotted, in every format: {@code
 * .properties} writes the keys as they are, the others nest them. JSON writes no comments.
 */
@ParameterizedClass(name = "{0}")
@MethodSource(Sources.ALL)
class TestDottedKeyComments extends Scenario {

  TestDottedKeyComments(Format format) {
    super(format, "comments");
  }

  @Test
  void commentsOfDottedKeysAreWritten() {
    assertDump("dotted-keys", new Message());
  }

  @Test
  void commentedDottedKeysLoad() {
    Message config = load(new Message(), "dotted-keys-read");
    Assertions.assertEquals(MessageType.COMPONENT, config.type);
    Assertions.assertEquals("foo bar baz", config.text);
  }

  // <editor-fold desc="subjects">

  enum MessageType {
    COMPONENT,
    STRING
  }

  @Comment("Test subject config. Can change at any time")
  @Comment("Generated by AnnotationConfig")
  static class Message {

    @Comment("The message that will be sent to the player")
    @Comment("Bla bla 2nd comment")
    @Key("message.text")
    String text = "this is a message";

    @Comment("The message sending strategy with which the message will be sent")
    @Key("message.type")
    MessageType type = MessageType.STRING;
  }

  // </editor-fold>
}
