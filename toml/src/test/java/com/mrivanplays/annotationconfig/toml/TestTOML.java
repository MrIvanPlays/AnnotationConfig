package com.mrivanplays.annotationconfig.toml;

import java.io.StringWriter;
import java.time.OffsetDateTime;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;

public class TestTOML {

  @Test
  public void testLoad() {
    TOMLTestSubject config = new TOMLTestSubject();
    TomlConfig.getConfigResolver()
        .load(config, getClass().getClassLoader().getResourceAsStream("test-toml.toml"));

    Assertions.assertEquals("Ivan", config.getName());
    Assertions.assertFalse(config.isBar());
    Assertions.assertEquals("localhost", config.getServer().getHipi());
    Assertions.assertEquals(25577, config.getServer().getPort());
    Assertions.assertEquals(
        OffsetDateTime.parse("2021-11-10T17:31:48.814610747+02:00"), config.getDateTime());
    Assertions.assertEquals("foo string", config.getTableWithDefaultSerialize().getFoo());
    Assertions.assertEquals(1, config.getTableWithDefaultSerialize().getBar());
    Assertions.assertEquals(0.555, config.getTableWithDefaultSerialize().getBaz());
  }

  @Test
  public void testDump() {
    StringWriter writer = new StringWriter();
    TomlConfig.getConfigResolver().dump(new TOMLTestSubject(), writer);
    String expected =
        "# Generated by AnnotationConfig v2.0.0\n"
            + "\n"
            + "# name\n"
            + "name = 'Ivan'\n"
            + "\n"
            + "# bar\n"
            + "bar = false\n"
            + "\n"
            + "# OffsetDateTime\n"
            + "dateTime = 2021-11-10T17:31:48+02:00\n"
            + "\n"
            + "# Server\n"
            + "[server]\n"
            + "ip = 'localhost'\n"
            + "theport = 25565\n"
            + "\n"
            + "# This has been dumped with the default serializer\n"
            + "[default-serializer]\n"
            + "foo = 'foo string'\n"
            + "bar = 1\n"
            + "baz = 0.555\n";
    Assertions.assertEquals(expected, writer.toString());
  }
}
